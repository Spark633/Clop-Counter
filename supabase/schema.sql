-- Clop Counter – Supabase schema
-- Run this once in the Supabase dashboard: SQL Editor → New query → paste → Run.
-- Accounts use only username + password: register() creates the auth user directly
-- with an internal pseudo e-mail, so no e-mail is ever needed or sent.

create extension if not exists pgcrypto with schema extensions;

-- ---------------------------------------------------------------- tables

create table if not exists public.profiles (
    id          uuid primary key references auth.users (id) on delete cascade,
    user_number bigint generated by default as identity (start with 10001) unique not null,
    username    text not null check (username ~ '^[A-Za-z0-9_.-]{3,20}$'),
    created_at  timestamptz not null default now()
);
create unique index if not exists profiles_username_lower on public.profiles (lower(username));

-- Hash of the recovery code that lets a user reset a forgotten password. Never readable by clients.
create table if not exists public.account_recovery (
    user_id   uuid primary key references auth.users (id) on delete cascade,
    code_hash text not null
);

create table if not exists public.entries (
    uuid       uuid primary key,
    user_id    uuid not null default auth.uid() references auth.users (id) on delete cascade,
    ts         bigint not null,              -- epoch millis
    epoch_day  bigint not null,              -- local calendar day
    tags       text[] not null default '{}',
    links      jsonb not null default '[]',  -- [{url, title, preview}]
    updated_at bigint not null
);
create index if not exists entries_user_day on public.entries (user_id, epoch_day);

-- Notes are private: kept separately so friends can never read them.
create table if not exists public.entry_notes (
    uuid    uuid primary key references public.entries (uuid) on delete cascade,
    user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
    note    text not null default ''
);

create table if not exists public.friendships (
    requester  uuid not null references public.profiles (id) on delete cascade,
    addressee  uuid not null references public.profiles (id) on delete cascade,
    accepted   boolean not null default false,
    created_at timestamptz not null default now(),
    primary key (requester, addressee),
    check (requester <> addressee)
);

alter table public.profiles         enable row level security;
alter table public.account_recovery enable row level security;
alter table public.entries          enable row level security;
alter table public.entry_notes      enable row level security;
alter table public.friendships      enable row level security;

-- ---------------------------------------------------------------- access rules

create or replace function public.is_friend(other uuid)
returns boolean language sql stable security definer set search_path = public as $$
    select exists (
        select 1 from public.friendships
        where accepted
          and ((requester = auth.uid() and addressee = other)
            or (addressee = auth.uid() and requester = other))
    );
$$;

drop policy if exists "profiles readable" on public.profiles;
create policy "profiles readable" on public.profiles
    for select to authenticated using (true);

drop policy if exists "entries readable by owner and friends" on public.entries;
create policy "entries readable by owner and friends" on public.entries
    for select to authenticated using (user_id = auth.uid() or public.is_friend(user_id));
drop policy if exists "entries insert own" on public.entries;
create policy "entries insert own" on public.entries
    for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "entries update own" on public.entries;
create policy "entries update own" on public.entries
    for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists "entries delete own" on public.entries;
create policy "entries delete own" on public.entries
    for delete to authenticated using (user_id = auth.uid());

drop policy if exists "notes own" on public.entry_notes;
create policy "notes own" on public.entry_notes
    for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "friendships visible to both" on public.friendships;
create policy "friendships visible to both" on public.friendships
    for select to authenticated using (auth.uid() in (requester, addressee));
-- Friendships are only changed through the functions below; account_recovery has no policies at all.

-- ---------------------------------------------------------------- accounts

create or replace function public.register(p_username text, p_password text, p_recovery_code text)
returns bigint language plpgsql security definer set search_path = public, extensions, auth as $$
declare
    new_id uuid := gen_random_uuid();
    mail   text;
    new_number bigint;
begin
    if p_username !~ '^[A-Za-z0-9_.-]{3,20}$' then raise exception 'invalid_username'; end if;
    if length(p_password) < 6 then raise exception 'weak_password'; end if;
    if exists (select 1 from public.profiles where lower(username) = lower(p_username)) then
        raise exception 'username_taken';
    end if;

    mail := lower(p_username) || '@users.clopcounter.invalid';

    insert into auth.users (
        instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
        raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
        confirmation_token, recovery_token, email_change_token_new, email_change
    ) values (
        '00000000-0000-0000-0000-000000000000', new_id, 'authenticated', 'authenticated', mail,
        crypt(p_password, gen_salt('bf')), now(),
        '{"provider":"email","providers":["email"]}', jsonb_build_object('username', p_username), now(), now(),
        '', '', '', ''
    );
    insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
    values (gen_random_uuid(), new_id, new_id::text,
            jsonb_build_object('sub', new_id::text, 'email', mail, 'email_verified', true),
            'email', now(), now(), now());

    insert into public.profiles (id, username) values (new_id, p_username) returning user_number into new_number;
    insert into public.account_recovery (user_id, code_hash)
    values (new_id, crypt(upper(regexp_replace(p_recovery_code, '[^A-Za-z0-9]', '', 'g')), gen_salt('bf')));
    return new_number;
end $$;

create or replace function public.reset_password(p_username text, p_recovery_code text, p_new_password text)
returns boolean language plpgsql security definer set search_path = public, extensions, auth as $$
declare
    uid  uuid;
    hash text;
begin
    if length(p_new_password) < 6 then raise exception 'weak_password'; end if;
    select p.id, r.code_hash into uid, hash
    from public.profiles p join public.account_recovery r on r.user_id = p.id
    where lower(p.username) = lower(p_username);
    if uid is null
       or hash <> crypt(upper(regexp_replace(p_recovery_code, '[^A-Za-z0-9]', '', 'g')), hash) then
        return false;
    end if;
    update auth.users set encrypted_password = crypt(p_new_password, gen_salt('bf')), updated_at = now()
    where id = uid;
    return true;
end $$;

create or replace function public.delete_account()
returns void language sql security definer set search_path = public, auth as $$
    delete from auth.users where id = auth.uid();
$$;

-- ---------------------------------------------------------------- friends

create or replace function public.send_friend_request(p_target text)
returns text language plpgsql security definer set search_path = public as $$
declare
    me    uuid := auth.uid();
    other uuid;
    t     text := trim(p_target);
begin
    if me is null then raise exception 'not_authenticated'; end if;
    if t ~ '^#?[0-9]{1,15}$' then
        select id into other from public.profiles where user_number = ltrim(t, '#')::bigint;
    end if;
    if other is null then
        select id into other from public.profiles where lower(username) = lower(ltrim(t, '@'));
    end if;
    if other is null then return 'not_found'; end if;
    if other = me then return 'self'; end if;

    if exists (select 1 from public.friendships where requester = other and addressee = me) then
        update public.friendships set accepted = true where requester = other and addressee = me;
        return 'accepted';
    end if;
    if exists (select 1 from public.friendships where requester = me and addressee = other) then
        return 'already_sent';
    end if;
    insert into public.friendships (requester, addressee) values (me, other);
    return 'sent';
end $$;

create or replace function public.respond_friend_request(p_other uuid, p_accept boolean)
returns void language plpgsql security definer set search_path = public as $$
begin
    if p_accept then
        update public.friendships set accepted = true where requester = p_other and addressee = auth.uid();
    else
        delete from public.friendships where requester = p_other and addressee = auth.uid();
    end if;
end $$;

create or replace function public.remove_friend(p_other uuid)
returns void language sql security definer set search_path = public as $$
    delete from public.friendships
    where (requester = auth.uid() and addressee = p_other)
       or (requester = p_other and addressee = auth.uid());
$$;

create or replace function public.my_friends()
returns table (user_id uuid, username text, user_number bigint, status text)
language sql stable security definer set search_path = public as $$
    select p.id, p.username, p.user_number,
           case when f.accepted then 'friend'
                when f.requester = auth.uid() then 'outgoing'
                else 'incoming' end
    from public.friendships f
    join public.profiles p
      on p.id = case when f.requester = auth.uid() then f.addressee else f.requester end
    where auth.uid() in (f.requester, f.addressee)
    order by lower(p.username);
$$;

-- ---------------------------------------------------------------- permissions

revoke execute on function public.register(text, text, text) from public;
revoke execute on function public.reset_password(text, text, text) from public;
grant execute on function public.register(text, text, text) to anon, authenticated;
grant execute on function public.reset_password(text, text, text) to anon, authenticated;

revoke execute on function public.delete_account() from public, anon;
revoke execute on function public.send_friend_request(text) from public, anon;
revoke execute on function public.respond_friend_request(uuid, boolean) from public, anon;
revoke execute on function public.remove_friend(uuid) from public, anon;
revoke execute on function public.my_friends() from public, anon;
grant execute on function public.delete_account() to authenticated;
grant execute on function public.send_friend_request(text) to authenticated;
grant execute on function public.respond_friend_request(uuid, boolean) to authenticated;
grant execute on function public.remove_friend(uuid) to authenticated;
grant execute on function public.my_friends() to authenticated;
